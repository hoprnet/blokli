//! Resolution of historical contract deployments from pinned bindings releases.
use std::{fmt, str::FromStr};

use hopr_types::primitive::prelude::Address;
use semver::Version;
use serde::{Deserialize, Serialize};

use crate::macros::historical_bindings;

// Catalog of historical contracts releases that can be listed in
// `indexer.additional_node_stake_factory_releases`.
//
// The catalog is EMPTY by default: the mechanism for indexing several StakeFactory deployments is in place, but no
// historical release is bundled. The active `hopr-bindings` dependency is a caret range, so it must never be listed
// here under a tag it may not match.
//
// To add a release `vX.Y.Z`:
//   1. declare an exactly pinned alias in the workspace and `bloklid` Cargo.toml, e.g. `hopr-bindings-vX-Y-Z = {
//      package = "hopr-bindings", version = "=X.Y.Z" }`
//   2. add an entry below: `"vX.Y.Z" => hopr_bindings_vX_Y_Z,`
// The unit tests generated by the macro then check the manifest and ABI compatibility of the new entry.
historical_bindings! {}

/// A canonical GitHub contracts release tag such as `v1.2.3`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct ContractsRelease(String);

impl ContractsRelease {
    /// Returns the canonical release tag.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for ContractsRelease {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

impl FromStr for ContractsRelease {
    type Err = String;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        let version = value
            .strip_prefix('v')
            .ok_or_else(|| "contracts release must start with 'v'".to_string())?;
        let version =
            Version::parse(version).map_err(|error| format!("invalid contracts release '{value}': {error}"))?;

        Ok(Self(format!("v{version}")))
    }
}

impl TryFrom<String> for ContractsRelease {
    type Error = String;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        value.parse()
    }
}

impl From<ContractsRelease> for String {
    fn from(value: ContractsRelease) -> Self {
        value.0
    }
}

/// StakeFactory metadata normalized across historical bindings crate versions.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StakeFactoryDeployment {
    /// Address of the historical StakeFactory.
    pub address: Address,
    /// Chain ID declared by the historical network manifest.
    pub chain_id: u64,
    /// Safe lower bound from which the historical release should be indexed.
    pub indexer_start_block_number: u32,
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Test-only catalog that exercises the macro against the bindings crate this binary is built with.
    /// The key is only a label here; production catalog entries must use exactly pinned aliases.
    mod catalog {
        use hopr_types::primitive::prelude::Address;

        use super::{ContractsRelease, StakeFactoryDeployment};
        use crate::macros::historical_bindings;

        historical_bindings! {
            "v0.0.0-test" => hopr_bindings,
        }
    }

    #[test]
    fn test_default_catalog_is_empty() {
        let release = "v5.0.0".parse::<ContractsRelease>().unwrap();
        assert!(resolve_stake_factory(&release, "jura-dev").is_none());
    }

    #[test]
    fn test_unknown_release_is_not_resolved_by_catalog() {
        let release = "v1.2.3".parse::<ContractsRelease>().unwrap();
        assert!(catalog::resolve_stake_factory(&release, "jura-dev").is_none());
    }

    #[test]
    fn test_contracts_release_parsing() {
        assert_eq!(
            "v1.2.3"
                .parse::<ContractsRelease>()
                .expect("release should parse")
                .as_str(),
            "v1.2.3"
        );
        assert_eq!(
            "v1.0.0-rc.1"
                .parse::<ContractsRelease>()
                .expect("pre-release should parse")
                .as_str(),
            "v1.0.0-rc.1"
        );
        assert!("1.2.3".parse::<ContractsRelease>().is_err());
        assert!("vnot-a-version".parse::<ContractsRelease>().is_err());
    }
}
